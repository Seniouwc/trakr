//! Every user-visible command, in one list. Keys, menus and toolbars all map to these,
//! so a feature added here shows up everywhere with its shortcut.

use crate::keys::{KeyCode, KeyEvent};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Action {
    // file
    New,
    Save,
    Quit,
    // edit
    Undo,
    Redo,
    Cut,
    Copy,
    Paste,
    Clear,
    SelectAll,
    SelectNone,
    ToggleEdit,
    // block
    TransposeUp,
    TransposeDown,
    TransposeOctaveUp,
    TransposeOctaveDown,
    Reverse,
    Interpolate,
    InsertLine,
    DeleteLine,
    // transport
    PlaySong,
    PlayPattern,
    PlayFromCursor,
    Stop,
    ToggleFollow,
    // sequence
    SeqPrev,
    SeqNext,
    SeqInsert,
    SeqClone,
    SeqDelete,
    SeqMoveUp,
    SeqMoveDown,
    PatternPrev,
    PatternNext,
    // tracks
    TrackAdd,
    TrackRemove,
    TrackMute,
    NoteColumnAdd,
    NoteColumnRemove,
    EffectColumnAdd,
    EffectColumnRemove,
    // settings
    OctaveDown,
    OctaveUp,
    StepDown,
    StepUp,
    InstrumentPrev,
    InstrumentNext,
    InstrumentRemove,
    RecordToggle,
    RenderToSample,
    FadeInBlock,
    FadeOutBlock,
    TrackSolo,
    LoopStart,
    LoopEnd,
    LoopClear,
}

